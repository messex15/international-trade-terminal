// Copies the portal component rules the client-facing /freight/ page needs out
// of /styles.css (which _redirects keeps members-only) into
// /freight/portal-kit.css. Run again after changing styles.css:
//   node scripts/build-portal-kit.mjs
import { readFileSync, writeFileSync } from "node:fs";

const ALLOWED = new Set([
  "brandMark", "brandWords", "iconButton", "contentArea", "pageHead", "headActions", "primary", "secondary",
  "card", "cardTitle", "dataCard", "toolbar", "pageSearch", "filterSelect", "recordCount", "tableWrap",
  "emptyState", "badge", "good", "bad", "warn", "overlay", "centered", "drawer", "drawerHead", "drawerBody",
  "businessTag", "detailGrid", "detailBlock", "notice", "modal", "formGrid", "modalNote", "modalActions", "toast",
]);

const css = readFileSync(new URL("../styles.css", import.meta.url), "utf8").replace(/\r\n/g, "\n");

// Split into top-level blocks: "selector{...}" or "@media(...){...}".
function blocks(text) {
  const out = [];
  let i = 0;
  while (i < text.length) {
    const open = text.indexOf("{", i);
    if (open < 0) break;
    const head = text.slice(i, open).trim();
    let depth = 1;
    let j = open + 1;
    while (j < text.length && depth) {
      if (text[j] === "{") depth++;
      else if (text[j] === "}") depth--;
      j++;
    }
    out.push({ head, body: text.slice(open + 1, j - 1) });
    i = j;
  }
  return out;
}

function keep(selectorList) {
  return selectorList.split(",").every((sel) => {
    const classes = [...sel.matchAll(/\.([A-Za-z][\w-]*)/g)].map((m) => m[1]);
    return classes.every((c) => ALLOWED.has(c));
  });
}

const lines = [
  "/* Generated by scripts/build-portal-kit.mjs from /styles.css. Do not edit by hand.",
  "   The client-facing /freight/ page cannot load /styles.css (members only), so",
  "   this file carries the portal rules the Freight Desk uses, copied verbatim. */",
];
for (const { head, body } of blocks(css)) {
  if (head.startsWith("@media")) {
    const inner = blocks(body).filter((b) => keep(b.head)).map((b) => `${b.head}{${b.body.trim()}}`);
    if (inner.length) lines.push(`${head}{${inner.join("\n")}\n}`);
  } else if (keep(head)) {
    lines.push(`${head}{${body.trim()}}`);
  }
}
writeFileSync(new URL("../freight/portal-kit.css", import.meta.url), lines.join("\n") + "\n");
console.log(`portal-kit.css: ${lines.length - 3} blocks`);
